import { Siren } from "lucide-react";
import { useState } from "react";
import MissionPicker, { useMissionParam } from "../components/MissionPicker";
import ReviewControls from "../components/ReviewControls";
import { AIObservation, cx, Empty, ErrorNote, Panel, ReviewBadge, ScanLoader, Select, SeverityBadge } from "../components/ui";
import { human, latlon, pad3, pct, tplus } from "../lib/format";
import { navigate, useApi } from "../lib/hooks";
import type { AegisEvent } from "../lib/types";

export const EVENT_TYPES = ["ALL", "OBJECT_APPEARED", "OBJECT_DISAPPEARED", "SIGNIFICANT_MOVEMENT", "SCENE_CHANGE", "VEHICLE_COUNT_CHANGE",
  "CROWD_DENSITY_CHANGE", "MONITORING_ZONE_ENTRY", "MONITORING_ZONE_EXIT", "VIDEO_INTERRUPTION", "LOW_IMAGE_QUALITY"];

export default function Events() {
  const [mission, setMission, missions] = useMissionParam(false);
  const [type, setType] = useState("ALL");
  const [review, setReview] = useState("ALL");
  const [severity, setSeverity] = useState("ALL");
  const q = new URLSearchParams({ ...(mission !== null ? { mission_id: String(mission) } : {}), ...(type !== "ALL" ? { type } : {}),
    ...(review !== "ALL" ? { review } : {}), ...(severity !== "ALL" ? { severity } : {}) });
  const events = useApi<AegisEvent[]>(`/api/events?${q}`, { poll: 8000 });
  const [sel, setSel] = useState<AegisEvent | null>(null);
  const pending = (events.data || []).filter((e) => e.review_status === "UNVERIFIED" || e.review_status === "NEEDS_REVIEW").length;

  return (
    <div className="grid h-full grid-cols-1 gap-2 overflow-y-auto p-2 xl:grid-cols-[minmax(0,1fr)_380px] xl:overflow-hidden">
      <Panel title="EVENT ANALYSIS" icon={Siren} bodyClass="flex min-h-0 flex-col p-0" className="min-h-96"
        right={<span className="mono text-[10px] text-amber">{pending} REQUIRE HUMAN REVIEW</span>}>
        <div className="flex flex-wrap items-center gap-2 border-b border-line p-2">
          <MissionPicker value={mission} onChange={setMission} missions={missions} allowAll />
          <Select value={type} onChange={setType} options={EVENT_TYPES.map((t) => [t, human(t)] as [string, string])} label="Event type" />
          <Select value={severity} onChange={setSeverity} options={["ALL", "INFO", "WARNING", "HIGH", "CRITICAL"]} label="Severity" />
          <Select value={review} onChange={setReview} options={["ALL", "UNVERIFIED", "NEEDS_REVIEW", "CONFIRMED", "REJECTED"]} label="Review status" />
          <span className="mono ml-auto text-[10px] text-muted">{events.data?.length ?? 0} EVENTS</span>
        </div>
        {events.error && <div className="p-2"><ErrorNote error={events.error} /></div>}
        <div className="min-h-0 flex-1 overflow-auto">
          {!events.data ? <ScanLoader /> : events.data.length === 0 ? <Empty icon={Siren} title="NO EVENTS" hint="Events are generated by the EVENT AI stage." /> : (
            <table className="table">
              <thead><tr><th>Event ID</th><th>Mission</th><th>Time</th><th>Type</th><th>Confidence</th><th>Severity</th><th>Location</th><th>Related tracks</th><th>Evidence</th><th>Review status</th></tr></thead>
              <tbody>
                {events.data.map((e) => (
                  <tr key={e.id} className={cx("cursor-pointer", sel?.id === e.id && "selected")} onClick={() => setSel(e)}>
                    <td className="mono text-ink">{e.code}</td>
                    <td className="mono text-[10px] text-muted">{e.mission_code}</td>
                    <td className="mono tabular-nums">{tplus(e.timestamp_s)}</td>
                    <td className="mono text-[11px]">{human(e.type)}</td>
                    <td className="mono tabular-nums">{pct(e.confidence)}</td>
                    <td><SeverityBadge s={e.severity} /></td>
                    <td className="mono text-[10px] text-ink-2">{latlon(e.lat, e.lon)}</td>
                    <td className="mono text-[10px]">{e.related_tracks.slice(0, 4).map((n) => `#${pad3(n)}`).join(" ") || "—"}</td>
                    <td className="mono text-[10px]">{e.has_evidence ? `FRAME ${e.frame_index}` : "—"}</td>
                    <td><ReviewBadge s={e.review_status} /></td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      </Panel>
      <div className="flex min-h-0 flex-col gap-2 overflow-y-auto">
        {!sel ? <Panel title="EVENT DETAIL" icon={Siren}><div className="text-[12px] text-muted">Select an event to inspect its evidence frame and record an analyst review.</div></Panel> : (
          <Panel title={`${sel.code} · ${human(sel.type)}`} icon={Siren} right={<button className="btn btn-sm" onClick={() => navigate(`/analysis?mission=${sel.mission_id}&event=${sel.id}`)}>OPEN IN WORKSPACE</button>}>
            <div className="space-y-2">
              <AIObservation confidence={sel.confidence} status={sel.review_status} />
              {sel.has_evidence ? <img src={`/api/events/${sel.id}/evidence`} alt={`Evidence ${sel.code}`} className="w-full border border-line" /> : <div className="text-[11px] text-muted">No evidence frame.</div>}
              <div className="text-[12px] text-ink">{sel.description}</div>
              <div className="mono grid grid-cols-2 gap-1 text-[10px] text-ink-2">
                <span>MISSION {sel.mission_code}</span><span>TIME {tplus(sel.timestamp_s)}</span>
                <span>SEVERITY {sel.severity}</span><span>CONFIDENCE {pct(sel.confidence)}</span>
                <span className="col-span-2">LOCATION {latlon(sel.lat, sel.lon)}</span>
                <span className="col-span-2">RELATED TRACKS {sel.related_tracks.map((n) => `#${pad3(n)}`).join(" ") || "—"}</span>
              </div>
              {Object.keys(sel.details || {}).length > 0 && <pre className="mono max-h-24 overflow-auto bg-void p-2 text-[10px] text-muted">{JSON.stringify(sel.details, null, 1)}</pre>}
              <ReviewControls kind="events" id={sel.id} status={sel.review_status} notes={sel.analyst_notes} reviewedBy={sel.reviewed_by} reviewedAt={sel.reviewed_at}
                onSaved={(u) => { setSel(u); events.setData((l) => (l || []).map((x) => (x.id === u.id ? u : x))); }} />
            </div>
          </Panel>
        )}
      </div>
    </div>
  );
}
